const listeners = new Set();

function readStored() {
  try { return localStorage.getItem(STORAGE_KEY); } catch { return null; }
}

function detectInitial() {
  // Explicit ?lang= in shared links wins, then the saved preference, then the browser language.
  const fromUrl = new URLSearchParams(location.search).get('lang');
  if (SUPPORTED.includes(fromUrl)) {
    try { localStorage.setItem(STORAGE_KEY, fromUrl); } catch { /* storage unavailable */ }
    return fromUrl;
  }
  const stored = readStored();
  if (SUPPORTED.includes(stored)) return stored;
  return (navigator.language || 'id').toLowerCase().startsWith('id') ? 'id' : 'en';
}

let current = detectInitial();
document.documentElement.lang = current;

export const getLang = () => current;
export const languages = [{ code: 'id', label: 'Bahasa Indonesia' }, { code: 'en', label: 'English' }];

export function setLang(lang, { persist = true } = {}) {
  if (!SUPPORTED.includes(lang) || lang === current) return;
  current = lang;
  if (persist) {
    try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* storage unavailable (private mode) */ }
  }
  document.documentElement.lang = lang;
  listeners.forEach((listener) => listener(lang));
}

export function onLangChange(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

/** Translates a key; `{name}` placeholders are replaced from params (values are not escaped). */
export function t(key, params) {
  const value = DICTIONARY[current][key] ?? DICTIONARY.id[key] ?? key;
  if (!params || typeof value !== 'string') return value;
  return value.replace(/\{(\w+)\}/g, (_, name) => (name in params ? params[name] : `{${name}}`));
}
